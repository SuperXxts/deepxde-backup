#!/usr/bin/env bash
set -euo pipefail

PROJECT=/public/home/xinxi/wxtian/WXTIAN/PINN/deepxde/boundary_uncertainty_pinn
RUN_STAMP=${RUN_STAMP:-$(date +%Y%m%d_%H%M%S)}
GROUP=${GROUP:-02.FEMBenchmarkPreflight}
CASE=${CASE:-B0}
RUN_NAME=${RUN_NAME:-$CASE}
NODE=${NODE:-comput6}
DEVICE_INDEX=${DEVICE_INDEX:-0}

ITERATIONS=${ITERATIONS:-300}
DISPLAY_EVERY=${DISPLAY_EVERY:-100}
CHECKPOINT_EVERY=${CHECKPOINT_EVERY:-300}
NUM_DOMAIN=${NUM_DOMAIN:-120}
NUM_BOUNDARY=${NUM_BOUNDARY:-80}
OBS_COUNT=${OBS_COUNT:-30}
VAL_COUNT=${VAL_COUNT:-60}
TEST_NX=${TEST_NX:-31}
TEST_NY=${TEST_NY:-16}
REACTION_POINTS=${REACTION_POINTS:-20}
WIDTH=${WIDTH:-24}
DEPTH=${DEPTH:-2}
MATERIAL_WIDTH=${MATERIAL_WIDTH:-24}
MATERIAL_DEPTH=${MATERIAL_DEPTH:-2}
FEM_NX=${FEM_NX:-24}
FEM_NY=${FEM_NY:-12}
FEM_DATA_DIR=${FEM_DATA_DIR:-$PROJECT/exp/$GROUP/_fem_data}
RUN_NOTE=${RUN_NOTE:-FEM_B0_short_preflight}

RUN_DIR="$PROJECT/exp/$GROUP/$RUN_NAME"
SCREEN_NAME="bupinn_${RUN_NAME}_${RUN_STAMP}"

echo "preflight case=$CASE run_name=$RUN_NAME node=$NODE device=$DEVICE_INDEX run_dir=$RUN_DIR"
ssh "$NODE" "set -euo pipefail; cd '$PROJECT'; \
  rm -rf '$RUN_DIR' '$FEM_DATA_DIR'; \
  if screen -ls | grep -q '[.]$SCREEN_NAME[[:space:]]'; then echo 'ERROR: screen already exists: $SCREEN_NAME' >&2; exit 2; fi; \
  chmod +x hpc/run_fem_benchmark_onecase_lf.sh; \
  GROUP='$GROUP' RUN_STAMP='$RUN_STAMP' CASE='$CASE' RUN_NAME='$RUN_NAME' DEVICE_INDEX='$DEVICE_INDEX' \
  ITERATIONS='$ITERATIONS' DISPLAY_EVERY='$DISPLAY_EVERY' CHECKPOINT_EVERY='$CHECKPOINT_EVERY' \
  NUM_DOMAIN='$NUM_DOMAIN' NUM_BOUNDARY='$NUM_BOUNDARY' OBS_COUNT='$OBS_COUNT' VAL_COUNT='$VAL_COUNT' \
  TEST_NX='$TEST_NX' TEST_NY='$TEST_NY' REACTION_POINTS='$REACTION_POINTS' WIDTH='$WIDTH' DEPTH='$DEPTH' \
  MATERIAL_WIDTH='$MATERIAL_WIDTH' MATERIAL_DEPTH='$MATERIAL_DEPTH' FEM_NX='$FEM_NX' FEM_NY='$FEM_NY' \
  FEM_DATA_DIR='$FEM_DATA_DIR' RUN_NOTE='$RUN_NOTE' bash hpc/run_fem_benchmark_onecase_lf.sh"

echo "run_stamp=$RUN_STAMP"
echo "group=$GROUP"
echo "run=$RUN_NAME"
